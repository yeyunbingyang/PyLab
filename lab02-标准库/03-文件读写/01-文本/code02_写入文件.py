'''
============================================================
 文件写入: open + write/writelines (mode='w')
============================================================
对照笔记: 1.文件读写和异常处理.md — w 模式会先截断
============================================================
'''

# ═══════════════════════════════════════════════════════════════
# 1. mode='w' — 写入（覆盖已有内容）
#    write(s)     — 写入字符串
#    writelines() — 写入字符串列表
# ═══════════════════════════════════════════════════════════════
print("=" * 50)
print("【写入 mode='w' — 覆盖写】")
print("=" * 50)

f = open('test_w.txt', mode='w', encoding='utf-8')
f.write('你好，Python!\n')
f.write('文件写入第一行\n')
f.close()
print("  已写入 test_w.txt (覆盖模式)")

# ═══════════════════════════════════════════════════════════════
# 2. writelines() — 写入多行
# ═══════════════════════════════════════════════════════════════
print()
print("=" * 50)
print("【writelines() — 批量写入】")
print("=" * 50)

lines = ['第一行: 苹果\n', '第二行: 香蕉\n', '第三行: 橘子\n']
f = open('test_writelines.txt', mode='w', encoding='utf-8')
f.writelines(lines)
f.close()

# 验证
f = open('test_writelines.txt', mode='r', encoding='utf-8')
print("  写入内容:")
print(f.read().rstrip())
f.close()

# ═══════════════════════════════════════════════════════════════
# 3. mode='x' — 排他性创建（文件存在则报错）
# ═══════════════════════════════════════════════════════════════
print()
print("=" * 50)
print("【mode='x' — 排他创建】")
print("=" * 50)
try:
    f = open('test_exclusive.txt', mode='x', encoding='utf-8')
    f.write('这是排他模式创建的文件\n')
    f.close()
    print("  test_exclusive.txt 创建成功")
except FileExistsError:
    print("  文件已存在，mode='x' 抛出 FileExistsError")

# ═══════════════════════════════════════════════════════════════
# 4. 操作模式速查
# ═══════════════════════════════════════════════════════════════
print()
print("操作模式速查:")
print("  'r'  — 只读（默认）")
print("  'w'  — 只写，先截断文件（覆盖）")
print("  'x'  — 排他创建，文件存在则报错")
print("  'a'  — 追加，写入到文件末尾")
print("  'b'  — 二进制模式")
print("  't'  — 文本模式（默认）")
print("  '+'  — 更新（读写）")
print("  组合: 'rb', 'wb', 'ab', 'r+', 'w+', 'a+'")
