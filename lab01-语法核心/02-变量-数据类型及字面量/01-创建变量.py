# ======================================
# Python 变量创建与命名规范
# ======================================

# Python 是动态类型语言，变量无需提前声明类型，直接赋值即创建
# 变量的类型由所赋的值决定，且可以随时重新赋值为其他类型

# -------------------------
# 1. 变量命名规则
# -------------------------
# ① 只能包含：字母（a-z, A-Z）、数字（0-9）、下划线（_）
# ② 不能以数字开头
# ③ 不能是 Python 关键字（如 if, for, class, def 等）
# ④ 区分大小写（name 和 Name 是两个不同的变量）
# ⑤ 推荐使用有意义的英文命名，避免拼音或单字母

# -------------------------
# 2. 命名风格约定（PEP 8）
# -------------------------
#  小驼峰（lowerCamelCase）：普通变量、函数名、参数名
#    例：myName, totalPrice, userAge
#
#  大驼峰（UpperCamelCase / PascalCase）：类名
#    例：PersonInfo, HttpResponse, FileReader
#
#  全大写加下划线（SCREAMING_SNAKE_CASE）：常量
#    例：MAX_SIZE, PI, DEFAULT_TIMEOUT
#
#  下划线前缀：特殊用途变量（见下方说明）
# -------------------------


# ======================================
# 1. 基本变量赋值
# ======================================

price = 10.5     # float 类型：商品单价
weight = 7.5     # float 类型：商品重量
total = price * weight  # 变量参与运算，结果赋值给新变量
print("总共消费了 %.2f 元" % total)
# → 输出：总共消费了 78.75 元


# ======================================
# 2. 多重赋值
# ======================================

# 元组解包：等号左右数量必须一致
a, b = 10, 20
print(a, b)  # 10 20

# 交换变量的值（Python 特有写法，无需临时变量）
a, b = b, a
print(a, b)  # 20 10

# 链式赋值：多个变量指向同一个值
x = y = z = 0
print(x, y, z)  # 0 0 0


# ======================================
# 3. 动态类型特性
# ======================================

var = 10        # 此时是 int
print(type(var))  # <class 'int'>

var = "hello"   # 同一变量重新赋值为字符串
print(type(var))  # <class 'str'>

var = [1, 2, 3] # 再赋值为列表
print(type(var))  # <class 'list'>

# ⚠ 动态类型虽灵活，但过度复用变量名会降低可读性，建议避免


# ======================================
# 4. 变量命名风格示例
# ======================================

# --- 小驼峰（变量/函数） ---
myName = "张三"
userAge = 25
totalPrice = 99.99

# --- 大驼峰（类名） ---
# 此处仅作注释说明，类定义的示例在后续章节
# class PersonInfo:
#     pass

# --- 全大写（常量） ---
# Python 没有真正的常量机制，靠命名约定表示"不应修改"
PI = 3.1415926
MAX_CONNECTIONS = 100
DEFAULT_TIMEOUT = 30


# ======================================
# 5. 特殊变量命名
# ======================================

# --- 5.1 单下划线前缀（_xxx）---
# 约定为"保护"变量，仅在本模块内使用
# 在 from module import * 时不会被导入
_price = 10.5

# --- 5.2 双下划线前缀（__xxx）---
# 触发名称修饰（name mangling），用于避免子类意外覆盖
# 在类内部使用时会被重写为 _ClassName__xxx
__price = 10.5

# --- 5.3 双下划线前后缀（__xxx__）---
# 魔术方法 / 特殊方法，由 Python 内部定义
# 不要自定义这类命名
print(__name__)
# 直接运行此文件时输出：__main__
# 被导入时输出：模块名（如 01-创建变量）

# --- 5.4 单下划线后缀（xxx_）---
# 避免与关键字冲突
class_ = "Python 101"   # class 是关键字，加 _ 避免冲突
def_ = "函数定义"

# --- 5.5 单下划线本身（_）---
# 临时变量，表示"我不关心这个值"
for _ in range(3):
    print("循环执行一次")

# 解包时忽略某些值
person = ("张三", 25, "北京")
name, _, city = person  # 忽略年龄
print(name, city)  # 张三 北京


# ======================================
# 6. 全局变量
# ======================================

# 模块级变量，通常写在文件顶部
# 常量用全大写命名
PUBLIC_CONSTANT = "我是公开的全局变量"

# 函数内部访问全局变量需用 global 关键字声明
def show_global():
    global PUBLIC_CONSTANT  # 声明后才可以修改
    PUBLIC_CONSTANT = "我已被修改"
    print(PUBLIC_CONSTANT)

show_global()           # 我已被修改
print(PUBLIC_CONSTANT)  # 我已被修改（全局变量确实变了）

# ⚠ 尽量少用全局变量，会破坏函数的独立性和可测试性


# ======================================
# 7. 变量引用与垃圾回收
# ======================================

# Python 变量本质上是"标签"（引用），指向内存中的对象
a = [1, 2, 3]
b = a           # b 和 a 指向同一个列表对象
b.append(4)
print(a)        # [1, 2, 3, 4]（a 也变了）

# 判断是否为同一个对象
print(a is b)   # True

# 复制副本避免引用问题
c = a.copy()    # 浅拷贝
c.append(5)
print(a)        # [1, 2, 3, 4]（不受 c 影响）
print(c)        # [1, 2, 3, 4, 5]

# 删除变量（释放引用，对象由垃圾回收机制自动回收）
del a
