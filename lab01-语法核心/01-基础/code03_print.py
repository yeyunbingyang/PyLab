# ======================================
# 6. string.Template（模板字符串）
# ======================================
# 安全，适合处理用户输入的字符串（不会执行表达式）
# --------------------------------------

from string import Template

t = Template("你好，$name，你的余额是 $balance 元")
print(t.substitute(name="mia", balance=100))
# → 输出：你好，mia，你的余额是 100 元

# safe_substitute：缺失变量不报错，保留原样
print(t.safe_substitute(name="mia"))
# → 输出：你好，mia，你的余额是 $balance 元

# 用字典批量替换
data = {"name": "mia", "balance": 888}
print(t.substitute(data))
# → 输出：你好，mia，你的余额是 888 元
