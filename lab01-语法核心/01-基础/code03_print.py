# ======================================
# 1. print() 函数的使用
# ======================================

year = 2024  # 年份（整数类型 int）
month = 2    # 月份
day = 20     # 日期
week = "一"  # 星期几（字符串类型 str）
weather = "晴"  # 天气
temp = 19.5     # 温度（浮点数 float）

print("我是 mia")  # 最简单的输出语句：直接打印一个字符串

# @overload def print(*values: object,
#                     sep: str | None = " ",
#                     end: str | None = "\n",
#                     file: SupportsWrite[str] | None = None,
#                     flush: Literal[False] = False) -> None

# --------------------------------------
# print() 函数的参数详解：
# print(内容1, 内容2, ..., sep="分隔符", end="结尾")
#
# ① sep：设置多个内容之间的分隔符（默认是空格 " "）
# ② end：设置 print 执行后的结尾（默认是换行符 "\n"）
#
# 用法示例：
#   sep=""  → 去掉内容间的空格
#   end=""  → 不换行
#   end="——" → 自定义结尾符号
# --------------------------------------

print(year, "年，我要减肥", sep="")                     # sep="" 表示取消空格 → 2024年，我要减肥
print(year, "年，我要读100本书", sep="", end="\n")        # end="\n" 表示换行（默认）
print(year, "年，我要去10个城市旅游", sep="", end="\n\n")  # end="\n\n" 表示空一行（两次换行）

# print(1,"2",sep=1)
# TypeError: sep must be None or a string, not int

# --------------------------------------
# 使用格式化输出（% 占位符）
# print("格式字符串" % (变量组))
#
# 常用占位符：
#   %d    → 整数（decimal）
#   %02d  → 整数，不足两位补 0（0 是填充符，2 是宽度）
#   %s    → 字符串（string）
#   %.1f  → 浮点数（float），保留 1 位小数
#
# 语法原理：
#   “格式字符串”中使用占位符 % 表示替换位置，
#   右边以元组形式 (var1, var2, …) 传入实际值。
# --------------------------------------

print("今天是 %d 年 %02d 月 %d 日, 星期%s, 天气%s，温度 %.1f" %
      (year, month, day, week, weather, temp))
# 输出：今天是 2024 年 02 月 20 日, 星期一, 天气晴，温度 19.5


# ======================================
# 2. 格式化输出（% 格式符详解）
# ======================================

name = 'mia'       # 姓名（字符串）
age = 25           # 年龄（整数）
num = 1            # 编号
price = 8999.99    # 单价（浮点数）
discount = 0.1     # 折扣（0.1 = 10%）
octal_num = 10     # 用于演示八进制
hex_num = 255      # 用于演示十六进制


# -------------------------
# 各种格式符的说明
# -------------------------
# %s ：字符串（string）
# %d ：整数（decimal）
# %f ：浮点数（float）→ 默认保留 6 位小数，可用 %.2f 指定精度
# %o ：八进制数（octal）
# %x ：十六进制（小写）
# %X ：十六进制（大写）
# %e ：科学计数法（exponential）
# %06d：宽度为 6，不足补 0
# %.2f ：保留 2 位小数，四舍五入
# -------------------------

print("我的名字是 %s" % name)
# → 输出：我的名字是 mia

print("我的年龄是 %d" % age)
# → 输出：我的年龄是 25

print("我的编号是 %06d" % num)
# %06d 详解：
#   %  ：占位符开始
#   0  ：用 0 填充
#   6  ：宽度为 6 位
#   d  ：整数类型
# 实际输出：000001

print("%6d" % 1)     # → 输出：     1（右对齐，不补 0）
print("%06d" % -42)  # → 输出：-00042（负号占一位）

print("手机单价是 %.2f" % price)
# → 输出：手机单价是 8999.99

print("折扣是 %.2f%%" % (discount * 100))
# “%%” 输出一个真正的 % 符号
# → 输出：折扣是 10.00%

print("八进制是 %o" % octal_num)
# → 输出：八进制是 12（十进制 10 → 八进制 12）

print("小写十六进制是 %x" % hex_num)
# → 输出：小写十六进制是 ff

print("大写十六进制是 %X" % hex_num)
# → 输出：大写十六进制是 FF

print("科学计数法是 %e" % price)
# → 输出：科学计数法是 8.999990e+03（即 8.999990 × 10³）

print("我的名字是 %s, 我的年龄是 %d" % (name, age))
# → 输出：我的名字是 mia, 我的年龄是 25


# ======================================
# 3. f-string（推荐写法，Python 3.6+）
# ======================================

num = 1
print(f"我的编号是 {num:06d}")   # :06d 表示补零至 6 位
# → 输出：我的编号是 000001

price = 8999.99
print(f"手机单价是 {price:.2f}")  # 保留 2 位小数
# → 输出：手机单价是 8999.99

discount = 0.1
print(f"折扣是 {discount * 100:.1f}%")  # 显示 1 位小数
# → 输出：折扣是 10.0%


# ======================================
# 4. str.format()（Python 2.6+）
# ======================================
# 按位置、索引、关键字传入变量
# --------------------------------------

print("我的名字是 {}, 年龄是 {}".format(name, age))
# → 输出：我的名字是 mia, 年龄是 25

print("我的名字是 {0}, 年龄是 {1}".format(name, age))
# → 输出：我的名字是 mia, 年龄是 25

print("我的名字是 {n}, 年龄是 {a}".format(n=name, a=age))
# → 输出：我的名字是 mia, 年龄是 25

print("编号 {0:06d}, 价格 {1:.2f}".format(num, price))
# → 输出：编号 000001, 价格 8999.99

# 格式模板可以单独存储，便于复用
fmt = "今天是 %d 年 %02d 月 %d 日"
print(fmt % (year, month, day))

fmt = "今天是 {} 年 {:02d} 月 {} 日"
print(fmt.format(year, month, day))

# 通过字典解包传入（**dict）
data = {"n": "mia", "a": 25}
print("我的名字是 {n}, 年龄是 {a}".format(**data))
# → 输出：我的名字是 mia, 年龄是 25


