"""
Python 元组（Tuple）学习示例

"""

# =========================================================
# 一、元组的创建与定义
# =========================================================

# 创建元组：常规元组使用圆括号
colors = ("red", "green", "blue")
print("colors 元组:", colors)

# 创建单元素元组：注意要加上逗号
single = (42,)  # 这是一个元组，不是整数
print("单元素元组:", single)

# 元组包含多个元素，且这些元素不可变
t1 = (35, 12, 98)
t2 = ('骆昊', 43, True, '四川成都')

print("\nt1类型:", type(t1))  # <class 'tuple'>
print("t2类型:", type(t2))  # <class 'tuple'>

# =========================================================
# 二、元组的基本操作
# =========================================================

# 获取元组的长度
print("t1 元组的长度:", len(t1))  # 3
print("t2 元组的长度:", len(t2))  # 4

# 索引运算：获取元组中指定位置的元素
print("t1 第1个元素:", t1[0])   # 35
print("t1 第3个元素:", t1[2])   # 98
print("t2 最后一个元素:", t2[-1])  # 四川成都

# 切片运算：获取部分元组
print("t2 前两个元素:", t2[:2])  # ('骆昊', 43)
print("t2 每隔3个元素取一次:", t2[::3])  # ('骆昊', '四川成都')

# 循环遍历元组中的元素
print("\nt1 元素遍历:")
for elem in t1:
    print(elem)

# 成员运算：判断元素是否在元组中
print("\n12 在 t1 中:", 12 in t1)     # True
print("99 在 t1 中:", 99 in t1)     # False
print("'Hao' 不在 t2 中:", 'Hao' not in t2)  # True

# 拼接运算：将两个元组合并成一个元组
t3 = t1 + t2
print("\nt1 和 t2 拼接后的结果:", t3)
# (35, 12, 98, '骆昊', 43, True, '四川成都')

# 比较运算：比较两个元组的大小
print("t1 是否等于 t3:", t1 == t3)  # False
print("t1 是否大于等于 t3:", t1 >= t3)  # False
print("t1 是否小于等于 (35, 11, 99):", t1 <= (35, 11, 99))  # False

# =========================================================
# 三、元组的打包与解包
# =========================================================

# 打包操作：多个值赋给一个变量会自动打包成元组
a = 1, 10, 100
print("\n打包后的元组 a:", a)  # (1, 10, 100)

# 解包操作：将元组中的元素分别赋给多个变量
i, j, k = a
print("解包后的变量 i, j, k:", i, j, k)  # 1 10 100

# 如果解包时元素与变量个数不匹配，会报错
# a = 1, 10, 100, 1000
# i, j, k = a  # ValueError: too many values to unpack

# 使用星号表达式接收多个值
i, j, *k = a
print("星号解包后的结果:", i, j, k)  # 1 10 [100]

i, *j, k = a
print("星号解包后的结果:", i, j, k)  # 1 [10] 100

*i, j, k = a
print("星号解包后的结果:", i, j, k)  # [1] 100 1000

# =========================================================
# 四、交换变量值
# =========================================================

# 使用解包方式交换两个变量的值
a, b = 10, 20
print("\n交换前: a =", a, ", b =", b)

a, b = b, a  # 交换a和b的值
print("交换后: a =", a, ", b =", b)

# 使用类似方式交换三个变量的值
a, b, c = 1, 2, 3
print("\n交换前: a =", a, ", b =", b, ", c =", c)

a, b, c = b, c, a  # 三个变量互换
print("交换后: a =", a, ", b =", b, ", c =", c)

# =========================================================
# 五、元组与列表的比较
# =========================================================

# 元组和列表的比较
# 元组是不可变类型，而列表是可变类型

# 创建一个时间记录并比较
import timeit

list_creation_time = timeit.timeit('[1, 2, 3, 4, 5, 6, 7, 8, 9]', number=10000000)
tuple_creation_time = timeit.timeit('(1, 2, 3, 4, 5, 6, 7, 8, 9)', number=10000000)

print("\n创建列表花费时间:", list_creation_time, "秒")
print("创建元组花费时间:", tuple_creation_time, "秒")

# =========================================================
# 六、元组与列表的相互转换
# =========================================================

# 将元组转换为列表
infos = ('骆昊', 43, True, '四川成都')
infos_list = list(infos)
print("\n将元组转换为列表:", infos_list)

# 将列表转换为元组
frts = ['apple', 'banana', 'orange']
frts_tuple = tuple(frts)
print("将列表转换为元组:", frts_tuple)

